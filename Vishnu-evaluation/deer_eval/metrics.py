"""Per-run metrics.

Token definitions (used everywhere in the project, and in the report):
    reasoning_tokens  tokens before </think> (the chain of thought)
    answer_tokens     tokens after </think> (the final written answer)
    output_tokens     reasoning + answer. This is what DEER's check.py calls
                      "token_num" and what the paper reports as length.
    trial_tokens      tokens generated by DEER's trial-answer probes. Only
                      known for runs from our logged script; 0 otherwise.
    compute_tokens    output_tokens + trial_tokens (all generated tokens).
"""
from collections import Counter, defaultdict

import numpy as np

from .scoring import extract_pred, is_correct, split_response


def _count(tokenizer, text):
    if not text:
        return 0
    return len(tokenizer.encode(text, add_special_tokens=False))


def _exit_reason(rec):
    if rec.get("exit_reason"):
        return rec["exit_reason"]
    # Flags written by the official vllm-deer.py
    if rec.get("high_prob"):
        return "confident"
    if rec.get("too_long"):
        return "budget"
    if rec.get("regular_end"):
        return "natural"
    return "unknown"


def annotate(records, benchmark_rows=None, tokenizer=None):
    """Grade each record and attach token counts and metadata.

    records: rows from a run .jsonl (official DEER, our logged DEER, or
        our full-CoT script). Must contain 'generated_responses' and
        'gold_answer'.
    benchmark_rows: the benchmark rows, used to attach 'level'/'subject'.
        Matched by 'idx' if present, else by position.
    tokenizer: needed only if the records do not already store token counts.
    """
    out = []
    for pos, rec in enumerate(records):
        text = rec["generated_responses"][0]
        reasoning, answer = split_response(text)
        r = dict(rec)
        r["idx"] = rec.get("idx", pos)
        r["pred"] = extract_pred(text)
        r["correct"] = is_correct(r["pred"], rec["gold_answer"])

        if "num_thinking_tokens" in rec and "num_answer_tokens" in rec:
            r["reasoning_tokens"] = rec["num_thinking_tokens"]
            r["answer_tokens"] = rec["num_answer_tokens"]
        else:
            if tokenizer is None:
                raise ValueError(
                    "Records have no stored token counts; pass a tokenizer "
                    "(e.g. --tokenizer deepseek-ai/DeepSeek-R1-Distill-Qwen-1.5B)."
                )
            r["reasoning_tokens"] = _count(tokenizer, reasoning)
            r["answer_tokens"] = _count(tokenizer, answer)
        r["output_tokens"] = r["reasoning_tokens"] + r["answer_tokens"]

        cps = rec.get("checkpoints") or []
        r["n_checkpoints"] = len(cps) if cps else rec.get("thinking_steps", 0)
        r["trial_tokens"] = sum(c.get("n_trial_tokens", 0) for c in cps)
        r["compute_tokens"] = r["output_tokens"] + r["trial_tokens"]
        r["exit_reason"] = _exit_reason(rec)

        if benchmark_rows is not None:
            row = benchmark_rows[r["idx"]]
            if row["problem"] != rec.get("question", row["problem"]):
                raise ValueError(f"Record {pos} does not match benchmark row {r['idx']}")
            for k in ("level", "subject"):
                if k in row:
                    r[k] = row[k]
        out.append(r)
    return out


def summarize(annotated, wall_time_s=None):
    n = len(annotated)
    if n == 0:
        return {"n": 0}
    acc = np.array([r["correct"] for r in annotated], dtype=float)
    reasoning = np.array([r["reasoning_tokens"] for r in annotated], dtype=float)
    output = np.array([r["output_tokens"] for r in annotated], dtype=float)
    compute = np.array([r["compute_tokens"] for r in annotated], dtype=float)
    s = {
        "n": n,
        "accuracy": float(acc.mean()),
        # 95% normal-approx interval; useful to see when two runs are a tie
        "accuracy_ci95": float(1.96 * np.sqrt(acc.mean() * (1 - acc.mean()) / n)),
        "avg_reasoning_tokens": float(reasoning.mean()),
        "median_reasoning_tokens": float(np.median(reasoning)),
        "avg_output_tokens": float(output.mean()),
        "avg_compute_tokens": float(compute.mean()),
        "avg_checkpoints": float(np.mean([r["n_checkpoints"] for r in annotated])),
        "exit_reasons": dict(Counter(r["exit_reason"] for r in annotated)),
    }
    if wall_time_s is not None:
        s["wall_time_s"] = float(wall_time_s)
        s["wall_time_per_question_s"] = float(wall_time_s) / n
    return s


def relative_to(summary, baseline):
    """Compare a run with a baseline (normally Full CoT on the same questions)."""
    return {
        "accuracy_delta": summary["accuracy"] - baseline["accuracy"],
        "token_reduction_ratio": 1 - summary["avg_output_tokens"] / baseline["avg_output_tokens"],
        "reasoning_token_reduction_ratio": 1 - summary["avg_reasoning_tokens"] / baseline["avg_reasoning_tokens"],
        "compute_token_reduction_ratio": 1 - summary["avg_compute_tokens"] / baseline["avg_compute_tokens"],
    }


def group_summary(annotated, key):
    """Summaries per value of `key` (e.g. 'level' or 'subject' on MATH)."""
    groups = defaultdict(list)
    for r in annotated:
        if key in r:
            groups[r[key]].append(r)
    return {k: summarize(v) for k, v in sorted(groups.items(), key=lambda kv: str(kv[0]))}
